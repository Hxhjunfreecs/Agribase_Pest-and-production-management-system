    const normalizeText = (value) => value.replace(/\s+/g, " ").trim().toLocaleLowerCase();
    const normalizedCatalog = Object.fromEntries(
        Object.entries(phraseCatalog).map(([language, phrases]) => [
            language,
            Object.fromEntries(
                Object.entries(phrases).map(([source, translated]) => [
                    normalizeText(source),
                    translated
                ])
            )
        ])
    );
    normalizedCatalog.en = {};
    const originalText = new WeakMap();
    const originalAttributes = new WeakMap();
    const originalTitle = document.title;
    const currentLanguage = () => document.documentElement.lang;

    function translateTextNodes(language) {
        const dictionary = normalizedCatalog[language] || {};
        const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
        let node;

        while ((node = walker.nextNode())) {
            const parent = node.parentElement;
            if (!parent || parent.closest("script, style, textarea, [contenteditable='true'], [data-no-translate], .theme-icon, .avatar, .brand-mark, .public-brand")) {
                continue;
            }

            if (parent.closest("[data-i18n]")) {
                continue;
            }

            if (!originalText.has(node)) {
                originalText.set(node, node.nodeValue);
            }

            const source = originalText.get(node);
            const trimmed = source.trim();
            const countMatch = normalizeText(trimmed).match(/^(\d+) requiring attention$/);
            const welcomeMatch = trimmed.match(/^Welcome,\s*(.+?)\.?$/i);
            const dateMatch = trimmed.match(/^([A-Z][a-z]{2}) (\d{1,2}), (\d{4})$/);
            const composite = source.split(/([·—])/).map((part) => {
                const partText = part.trim();
                const translatedPart = dictionary[normalizeText(partText)];
                return translatedPart
                    ? part.replace(partText, translatedPart)
                    : part;
            }).join("");
            const translated = dictionary[normalizeText(trimmed)] || (countMatch
                ? language === "fil"
                    ? `${countMatch[1]} nangangailangan ng pansin`
                    : language === "ceb"
                        ? `${countMatch[1]} nanginahanglan og pagtagad`
                        : null
                : welcomeMatch && language === "fil"
                    ? `Maligayang pagdating, ${welcomeMatch[1]}.`
                    : welcomeMatch && language === "ceb"
                        ? `Maayong pag-abot, ${welcomeMatch[1]}.`
                        : dateMatch
                            ? `${dictionary[normalizeText(dateMatch[1])] || dateMatch[1]} ${dateMatch[2]}, ${dateMatch[3]}`
                            : composite !== source
                                ? composite
                                : null);
            const replacement = translated
                ? source.replace(trimmed, translated)
                : source;

            if (node.nodeValue !== replacement) {
                node.nodeValue = replacement;
            }
        }
    }

    function translateAttributes(language) {
        const dictionary = normalizedCatalog[language] || {};

        document.querySelectorAll("input, button, select, textarea, [title], [aria-label], [placeholder], img[alt]").forEach((element) => {
            const saved = originalAttributes.get(element) || {};
            ["placeholder", "title", "aria-label", "alt"].forEach((attribute) => {
                if (!element.hasAttribute(attribute)) {
                    return;
                }
                if (!(attribute in saved)) {
                    saved[attribute] = element.getAttribute(attribute);
                }
                const source = saved[attribute];
                element.setAttribute(attribute, dictionary[normalizeText(source)] || source);
            });
            originalAttributes.set(element, saved);
        });

        const keyedTranslations = phraseCatalog[language] || {};
        document.querySelectorAll("[data-i18n-aria]").forEach((element) => {
            const translated = keyedTranslations[element.dataset.i18nAria];
            if (translated) {
                element.setAttribute("aria-label", translated);
            }
        });
        document.querySelectorAll("[data-i18n-title]").forEach((element) => {
            const translated = keyedTranslations[element.dataset.i18nTitle];
            if (translated) {
                element.setAttribute("title", translated);
            }
        });
            document.querySelectorAll("[data-i18n]").forEach((element) => {
                const translated = keyedTranslations[element.dataset.i18n];
                if (translated) {
                    element.textContent = translated;
                }
            });
    }

    const previousApply = window.applyAgriBaseLanguage;
    window.applyAgriBaseLanguage = (language) => {
        const selected = phraseCatalog[language] ? language : "en";
        if (typeof previousApply === "function") {
            previousApply(selected);
        } else {
            document.documentElement.lang = selected;
        }
        document.documentElement.lang = selected;
        translateTextNodes(selected);
        translateAttributes(selected);
        const titleBase = originalTitle.replace(/\s*·\s*AgriBase$/, "");
        const translatedTitle = normalizedCatalog[selected][normalizeText(titleBase)]
            || normalizedCatalog[selected][normalizeText(originalTitle)]
            || titleBase;
        document.title = originalTitle.endsWith("· AgriBase")
            ? `${translatedTitle} · AgriBase`
            : translatedTitle;
    };

    const initialLanguage = phraseCatalog[localStorage.getItem("agribase.language")]
        ? localStorage.getItem("agribase.language")
        : "en";
    window.applyAgriBaseLanguage(initialLanguage);

    // Translate text inserted later by interactive maps and page scripts.
    const observer = new MutationObserver((mutations) => {
        if (mutations.some((mutation) => mutation.addedNodes.length > 0)) {
            translateTextNodes(currentLanguage());
        }
    });
    observer.observe(document.body, { childList: true, subtree: true });
